/* =========================================================
   ПРОВЕРКА
========================================================= */

function performCheck(key) {

    const order =
        state.currentOrder;

    const check =
        order.checks[key];


    if (!check) {

        return;
    }


    if (
        order.history.some(
            item =>
                item.key === key
        )
    ) {

        showToast(
            "Эта проверка уже выполнена"
        );

        return;
    }


    if (
        state.equipment <
        check.equipment
    ) {

        showToast(
            "🧰 Недостаточно ресурса оборудования"
        );

        return;
    }


    addTime(
        check.time
    );

    useEquipment(
        check.equipment
    );


    const result =
        check.results[
            order.correctCause
        ];


    order.history.push({

        key:
            key,

        name:
            check.name,

        result:
            result,

        time:
            check.time,

        equipment:
            check.equipment
    });


    save();

    openDiagnosis();
}


