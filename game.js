/* =========================================================
   ЦЕНА
========================================================= */

function offerRepair() {

    const order =
        state.currentOrder;

    const repair =
        order.problem.repairs[
            order.selectedCause
        ];


    const cost =
        repair.partCost +
        repair.workCost;


    const price =
        Number(
            $("repairPrice").value
        );


    if (
        !price ||
        price < cost
    ) {

        showToast(
            "Цена ниже себестоимости"
        );

        return;
    }


    const markup =
        (price - cost) /
        cost;


    let chance =
        0.95 -
        markup *
        order.client.priceSensitivity;


    chance =
        Math.max(
            0.10,
            Math.min(
                0.95,
                chance
            )
        );


    const accepted =
        Math.random() <
        chance;


    order.repair = {

        name:
            repair.name,

        partCost:
            repair.partCost,

        workCost:
            repair.workCost,

        time:
            repair.time,

        cost:
            cost,

        price:
            price,

        profit:
            price - cost
    };


    if (!accepted) {

        save();

        openModal(`

            <h2>❌ Клиент отказался</h2>

            <p>
                Клиент посчитал ремонт слишком дорогим.
            </p>

            <div class="diagnosis-result">

                💰 Диагностика всё равно оплачивается:
                <b>${money(order.diagnosisPrice)}</b>

            </div>

            <button
                class="action-button"
                onclick="finishDiagnosisOnly()">

                📋 Завершить заказ

            </button>

        `);

        return;
    }


    order.agreed =
        true;


    save();

    openModal(`

        <h2>✅ Клиент согласен</h2>

        <div class="stat-row">
            <span>Цена ремонта</span>
            <b>${money(price)}</b>
        </div>

        <div class="stat-row">
            <span>Себестоимость</span>
            <b>${money(cost)}</b>
        </div>

        <div class="stat-row">
            <span>Прибыль</span>
            <b>${money(price - cost)}</b>
        </div>

        <button
            class="action-button"
            onclick="performRepair()">

            🔧 Начать ремонт

        </button>

    `);
}


