function showToast(text) {

    const toast =
        $("toast");

    toast.textContent =
        text;

    toast.classList.add("show");

    clearTimeout(
        window.toastTimer
    );

    window.toastTimer =
        setTimeout(
            () => {
                toast.classList.remove("show");
            },
            2500
        );
}


