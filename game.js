function generateOrder() {

    let problem;

    let attempts = 0;

    do {

        problem =
            random(problems);

        attempts++;

    } while (
        problem.id === state.lastProblemId
        && attempts < 10
    );


    const car =
        random(cars);

    const client =
        random(clients);

    const year =
        random(car.years);

    const mileage =
        randomInt(70000, 260000);

    const complaint =
        random(problem.complaints);

    const correctCause =
        randomWeighted(problem.causes);


    const scenario = {

        id:
            Date.now()
            + Math.random(),

        car: {

            brand:
                car.brand,

            model:
                car.model,

            year:
                year,

            mileage:
                mileage,

            icon:
                car.icon
        },

        client: client,

        problem: problem,

        complaint: complaint,

        correctCause:
            correctCause.id,

        diagnosisPrice:
            randomInt(600, 1200),

        checks: {},

        history: [],

        diagnosisComplete: false,

        selectedCause: null,

        repair: null,

        agreed: false,

        completed: false,

        knowledgeUsed: false,

        diagnosisPaid: false
    };


    Object.keys(
        problem.checks
    ).forEach(key => {

        scenario.checks[key] =
            problem.checks[key];
    });


    state.lastProblemId =
        problem.id;

    state.currentOrder =
        scenario;


    save();

    return scenario;
}


function randomWeighted(items) {

    const total =
        items.reduce(
            (sum, item) =>
                sum + item.probability,
            0
        );

    let value =
        Math.random() * total;

    for (
        const item of items
    ) {

        value -= item.probability;

        if (
            value <= 0
        ) {

            return item;
        }
    }

    return items[0];
}


